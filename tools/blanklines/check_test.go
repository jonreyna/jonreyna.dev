// findLines parses src and returns the lines check reports, with their rule numbers.
func findLines(t *testing.T, src string) []string {

	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "x.go", src, 0)
	if err != nil {
		t.Fatal(err)
	}

	findings := check(fset, "x.go", f, strings.Split(src, "\n"))
	got := make([]string, 0, len(findings))
	for _, fd := range findings {
		rule := "13"
		if fd.msg == msgClose {
			rule = "14"
		}

		got = append(got, fd.String()[len("x.go:"):strings.Index(fd.String(), ": ")]+"/"+rule)
	}

	if len(got) == 0 {
		return nil
	}

	return got
}

func TestCheck(t *testing.T) {

	t.Parallel()
	tests := []struct {
		name string
		src  string
		want []string // "line/rule"
	}{
		{
			name: "short body needs nothing",
			src:  "package p\n\nfunc f() int {\n\treturn 1\n}\n",
			want: nil,
		},
		{
			name: "one-line function needs nothing",
			src:  "package p\n\nfunc f() int { return 1 }\n",
			want: nil,
		},
		{
			name: "long body without a blank line",
			src:  "package p\n\nfunc f() {\n\ta := 1\n\tb := 2\n\tc := 3\n\t_ = a + b + c\n}\n",
			want: []string{"3/13"},
		},
		{
			name: "long body with a blank line",
			src:  "package p\n\nfunc f() {\n\n\ta := 1\n\tb := 2\n\tc := 3\n\t_ = a + b + c\n}\n",
			want: nil,
		},
		{
			name: "block followed by a statement",
			src:  "package p\n\nfunc f(x int) int {\n\n\tif x > 0 {\n\t\tx--\n\t}\n\treturn x\n}\n",
			want: []string{"7/14"},
		},
		{
			name: "block followed by a blank line",
			src:  "package p\n\nfunc f(x int) int {\n\n\tif x > 0 {\n\t\tx--\n\t}\n\n\treturn x\n}\n",
			want: nil,
		},
		{
			name: "nested closing braces need nothing",
			src:  "package p\n\nfunc f(x int) {\n\n\tfor x > 0 {\n\t\tif x > 1 {\n\t\t\tx--\n\t\t}\n\t}\n}\n",
			want: nil,
		},
		{
			name: "else on the closing line",
			src:  "package p\n\nfunc f(x int) int {\n\tif x > 0 {\n\t\tx--\n\t} else {\n\t\tx++\n\t}\n\n\treturn x\n}\n",
			want: []string{"3/13"},
		},
		{
			name: "function literal followed by a call's closing paren",
			src:  "package p\n\nfunc f(g func(func())) {\n\tg(func() {\n\t\t_ = 1\n\t})\n}\n",
			want: nil,
		},
		{
			name: "two functions without a blank line between",
			src:  "package p\n\nfunc f() {\n}\nfunc g() {}\n",
			want: []string{"4/14"},
		},
		{
			name: "composite literals are not blocks",
			src:  "package p\n\nvar xs = []struct{ a int }{\n\t{\n\t\ta: 1,\n\t},\n\t{\n\t\ta: 2,\n\t},\n}\n",
			want: nil,
		},
		{
			name: "switch closes before a return",
			src:  "package p\n\nfunc f(x int) int {\n\n\tswitch x {\n\tcase 1:\n\t\tx = 2\n\t}\n\treturn x\n}\n",
			want: []string{"8/14"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {

			t.Parallel()

			if got := findLines(t, tc.src); !slices.Equal(got, tc.want) {
				t.Errorf("got %v, want %v", got, tc.want)
			}
		})
	}
}

func TestFix(t *testing.T) {

	t.Parallel()
	tests := []struct {
		name, src, want string
	}{
		{
			name: "adds both kinds",
			src:  "package p\n\nfunc f(x int) int {\n\tif x > 0 {\n\t\tx--\n\t}\n\treturn x\n}\n",
			want: "package p\n\nfunc f(x int) int {\n\n\tif x > 0 {\n\t\tx--\n\t}\n\n\treturn x\n}\n",
		},
		{
			name: "leaves clean code alone",
			src:  "package p\n\nfunc f() int { return 1 }\n",
			want: "package p\n\nfunc f() int { return 1 }\n",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {

			t.Parallel()

			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, "x.go", tc.src, 0)
			if err != nil {
				t.Fatal(err)
			}

			findings := check(fset, "x.go", f, strings.Split(tc.src, "\n"))
			got := []byte(tc.src)
			if len(findings) > 0 {
				if got, err = fix(got, findings); err != nil {
					t.Fatal(err)
				}
			}

			if string(got) != tc.want {
				t.Errorf("got:\n%s\nwant:\n%s", got, tc.want)
			}
		})
	}
}

func TestGenerated(t *testing.T) {

	t.Parallel()
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{name: "marker", src: "// Code generated by stringer. DO NOT EDIT.\n\npackage p\n", want: true},
		{name: "no marker", src: "// Package p does things.\npackage p\n", want: false},
		{name: "marker after package", src: "package p\n\n// Code generated by x. DO NOT EDIT.\n", want: false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {

			t.Parallel()

			if got := generated([]byte(tc.src)); got != tc.want {
				t.Errorf("generated = %v, want %v", got, tc.want)
			}
		})
	}
}
