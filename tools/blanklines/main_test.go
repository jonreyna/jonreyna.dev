package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const messy = "package p\n\nfunc f(x int) int {\n\tif x > 0 {\n\t\tx--\n\t}\n\treturn x\n}\n"

func TestRun(t *testing.T) {

	t.Parallel()
	tests := []struct {
		name     string
		files    map[string]string // relative path -> source
		flags    []string
		wantCode int
		wantOut  string
		wantFile string // contents of a.go afterward, if set
	}{
		{name: "clean", files: map[string]string{"a.go": "package p\n"}, wantOut: "checked 1 file: no blank lines missing"},
		{name: "reports", files: map[string]string{"a.go": messy}, wantCode: exitFailure, wantOut: "a.go:3: add a blank line after the function signature (rule 13)"},
		{
			name: "fixes", files: map[string]string{"a.go": messy}, flags: []string{"-w"},
			wantOut:  "fixed 1 of 1 file: added 2 blank lines",
			wantFile: "package p\n\nfunc f(x int) int {\n\n\tif x > 0 {\n\t\tx--\n\t}\n\n\treturn x\n}\n",
		},
		{name: "skips testdata", files: map[string]string{"testdata/a.go": messy}, wantOut: "checked 0 files"},
		{name: "skips generated", files: map[string]string{"a.go": "// Code generated by x. DO NOT EDIT.\n\n" + messy}, wantOut: "no blank lines missing"},
		{name: "parse error", files: map[string]string{"a.go": "package"}, wantCode: exitFailure, wantOut: "parse"},
		{name: "bad flag", flags: []string{"-nope"}, wantCode: exitUsage},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {

			t.Parallel()

			dir := t.TempDir()
			for name, src := range tc.files {
				path := filepath.Join(dir, name)
				if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
					t.Fatal(err)
				}

				if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
					t.Fatal(err)
				}
			}

			var out bytes.Buffer
			code := run(append(tc.flags, dir), &out, &out)
			if code != tc.wantCode || !strings.Contains(out.String(), tc.wantOut) {
				t.Fatalf("exit %d, output %q; want exit %d and %q", code, out.String(), tc.wantCode, tc.wantOut)
			}

			if tc.wantFile != "" {
				got, err := os.ReadFile(filepath.Join(dir, "a.go"))
				if err != nil || string(got) != tc.wantFile {
					t.Errorf("a.go = %q, %v; want %q", got, err, tc.wantFile)
				}
			}
		})
	}
}
